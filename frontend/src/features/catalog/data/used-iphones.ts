export function getUsedIphoneDetail(slug: string): ProductDetail | undefined {
  const summary = USED_IPHONES.find((p) => p.slug === slug);
  if (!summary) return undefined;

  return {
    ...summary,
    description: `Authentic pre-owned ${summary.title}. Rigorously inspected through our certified 70-point hardware diagnostic test. True Tone display, Face ID, camera OIS stabilization, and battery health (${summary.batteryHealth}%) verified 100% functional. 100% iCloud clean, BTRC IMEI verified. Supported by our 7-day replacement guarantee and 2-year dedicated service warranty at Bashundhara City & Jamuna Future Park diagnostic centers.`,
    categoryId: 'cat-iphone-preowned',
    categoryName: summary.categoryName,
    variants: [
      {
        id: `var-${summary.slug}-128`,
        sku: `${summary.slug.toUpperCase()}-128`,
        name: `${summary.storage || '128GB'} / ${summary.color || 'Standard'} / ${summary.conditionGrade || 'Grade A'}`,
        price: summary.basePrice,
        originalPrice: summary.originalPrice,
        inStock: true,
        availableQuantity: 5,
      },
    ],
    images: [
      {
        id: `img-${summary.slug}-1`,
        url: summary.primaryImageUrl || '',
        altText: summary.title,
        isPrimary: true,
        displayOrder: 1,
      },
    ],
    specifications: {
      'Condition Grade': summary.conditionGrade || 'Grade A+',
      'Battery Health': `${summary.batteryHealth}% (Original Apple Battery)`,
      'Region Code': summary.regionVariant || 'LL/A (USA)',
      'SIM Slot': summary.regionVariant?.includes('Dual Physical') ? 'Dual Nano-SIM' : 'Nano-SIM + eSIM',
      'True Tone Display': 'Verified Active',
      'Face ID': '100% Operational',
      'iCloud Status': 'Clean / Unlocked',
      '3uTools Score': '98 - 100% Genuine Components',
      'Warranty Included': summary.warrantyText || '7 Days Replacement + 2 Years Free Service',
      'Package Includes': summary.boxIncluded ? 'Device, Original Box, Lightning/Type-C Cable, Store Cash Memo' : 'Device, Fast Charger Adapter, Type-C Cable, Store Cash Memo',
    },
  };
}
